class _RelayDashboardScreenState extends State<RelayDashboardScreen> {
  final TextEditingController _serverUrlCtrl = TextEditingController();
  final TextEditingController _nodeIdCtrl = TextEditingController();
  final TextEditingController _relayKeyCtrl = TextEditingController();
  final TextEditingController _testVideoCtrl = TextEditingController(
