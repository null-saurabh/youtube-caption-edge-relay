class ExtractedCaptionPayload {
  const ExtractedCaptionPayload({
    required this.text,
    required this.captionKind,
    this.videoTitle,
    this.languageCode = 'en',
  });

  final String text;
  final String captionKind;
  final String? videoTitle;
  final String languageCode;
}

class ResidentialCaptionExtractor {
  static const int maxTranscriptBytes = 1024 * 1024;

  Future<ExtractedCaptionPayload> extract(String videoId) async {
    final youtube = YoutubeExplode();
    try {
      final titleFuture = youtube.videos
          .get(videoId)
          .timeout(const Duration(seconds: 10))
          .then<String?>((v) => v.title.trim())
          .catchError((Object _) => null);

      final manifest = await youtube.videos.closedCaptions
          .getManifest(videoId)
          .timeout(const Duration(seconds: 18));
      final tracks = manifest.tracks.toList();
      if (tracks.isEmpty) {
        tracks.addAll(await _tracksFromWatchPage(videoId));
      }
      if (tracks.isEmpty) {
        throw const FormatException('no_caption_tracks_available');
      }

      tracks.sort(_compareTracks);
      for (final selected in tracks) {
        try {
          final track = await youtube.videos.closedCaptions
              .get(selected)
              .timeout(const Duration(seconds: 25));
          final formatted = _formatCaptions(track.captions);
          if (formatted.trim().isEmpty) continue;
          return ExtractedCaptionPayload(
            text: formatted,
            captionKind: selected.isAutoGenerated ? 'auto' : 'manual',
            videoTitle: await titleFuture,
            languageCode: selected.language.code,
          );
        } catch (_) {
          continue;
        }
      }
      throw const FormatException('all_caption_tracks_empty');
    } finally {
      youtube.close();
    }
  }

  static int _compareTracks(
    ClosedCaptionTrackInfo a,
    ClosedCaptionTrackInfo b,
  ) {
    final genA = a.isAutoGenerated ? 1 : 0;
    final genB = b.isAutoGenerated ? 1 : 0;
    if (genA != genB) return genA - genB;
    return _langRank(a.language.code) - _langRank(b.language.code);
  }

  static int _langRank(String code) {
    final base = code.toLowerCase().split(RegExp(r'[-_]')).first;
    return switch (base) {
      'hi' => 0,
      'en' => 1,
      _ => 2,
    };
  }

  static String _formatCaptions(Iterable<ClosedCaption> captions) {
    final buf = StringBuffer();
    var bytes = 0;
    for (final c in captions) {
      final text = c.text.replaceAll(RegExp(r'\s+'), ' ').trim();
      if (text.isEmpty) continue;
      final line =
          '[${(c.offset.inMilliseconds / 1000).toStringAsFixed(1)}s] $text\n';
      final lineBytes = utf8.encode(line).length;
      if (bytes + lineBytes > maxTranscriptBytes) break;
      bytes += lineBytes;
      buf.write(line);
    }
    return buf.toString();
  }

  Future<List<ClosedCaptionTrackInfo>> _tracksFromWatchPage(
    String videoId,
  ) async {
    final response = await http
        .get(
          Uri.https('www.youtube.com', '/watch', {'v': videoId}),
          headers: const {
            'User-Agent':
                'Mozilla/5.0 (Linux; Android 13) AppleWebKit/537.36 '
                '(KHTML, like Gecko) Chrome/128.0.0.0 Mobile Safari/537.36',
            'Accept-Language': 'hi-IN,hi;q=0.9,en;q=0.8',
          },
        )
        .timeout(const Duration(seconds: 12));
    if (response.statusCode != 200 ||
        response.bodyBytes.length > 5 * 1024 * 1024) {
      return const [];
    }
    final body = utf8.decode(response.bodyBytes, allowMalformed: true);
    final playerResponse = _extractPlayerResponse(body);
    final captions = playerResponse?['captions'];
    if (captions is! Map) return const [];
    final renderer = captions['playerCaptionsTracklistRenderer'];
    if (renderer is! Map || renderer['captionTracks'] is! List) {
      return const [];
    }
    final result = <ClosedCaptionTrackInfo>[];
    for (final raw in renderer['captionTracks'] as List) {
      if (raw is! Map<String, dynamic>) continue;
      final baseUrl = raw['baseUrl'];
      final languageCode = raw['languageCode'];
      if (baseUrl is! String || languageCode is! String) continue;
      final rawName = raw['name'];
      final runs = rawName is Map ? rawName['runs'] as List? : null;
      final name = rawName is Map
          ? ((rawName['simpleText'] as String?) ??
                (runs != null && runs.isNotEmpty
                    ? runs.first['text'] as String? ?? ''
                    : ''))
          : '';
      result.add(
        ClosedCaptionTrackInfo.fromJson({
          'url': baseUrl,
          'language': {'code': languageCode, 'name': name},
          'isAutoGenerated':
              (raw['vssId'] as String?)?.toLowerCase().startsWith('a.') ??
              false,
          'format': {'formatCode': ClosedCaptionFormat.srv3.formatCode},
        }),
      );
    }
    return result;
  }

  Map<String, dynamic>? _extractPlayerResponse(String html) {
    final marker = RegExp(r'ytInitialPlayerResponse\s*=\s*').firstMatch(html);
    if (marker == null) return null;
    final start = html.indexOf('{', marker.end);
    if (start < 0) return null;
    var depth = 0;
    var inString = false;
    var escaped = false;
    for (var i = start; i < html.length; i++) {
      final char = html.codeUnitAt(i);
      if (inString) {
        if (escaped) {
          escaped = false;
        } else if (char == 0x5c) {
          escaped = true;
        } else if (char == 0x22) {
          inString = false;
        }
      } else if (char == 0x22) {
        inString = true;
      } else if (char == 0x7b) {
        depth++;
      } else if (char == 0x7d && --depth == 0) {
        try {
          final decoded = jsonDecode(html.substring(start, i + 1));
          return decoded is Map<String, dynamic> ? decoded : null;
        } on FormatException {
          return null;
        }
      }
    }
    return null;
  }
}

