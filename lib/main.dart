  final Set<String> _inFlightVideos = <String>{};
  final List<RelayLogEntry> _logs = <RelayLogEntry>[];

  Timer? _pollTimer;
  bool _running = false;
  bool _keepScreenAwake = true;
  int _pollIntervalMs = 1200;
  int _heartbeatsSent = 0;
  int _jobsCompleted = 0;
  int _jobsFailed = 0;
  int _clusterOnlineNodes = 0;
  DateTime? _lastPollAt;

  @override
  void initState() {
    super.initState();
    _initForegroundService();
    _loadSettings();
  }

  void _initForegroundService() {
    FlutterForegroundTask.init(
      androidNotificationOptions: AndroidNotificationOptions(
        channelId: 'caption_edge_relay_channel',
        channelName: 'Caption Edge Relay Worker',
        channelDescription:
            'Keeps the residential caption relay worker active in the background.',
        channelImportance: NotificationChannelImportance.LOW,
        priority: NotificationPriority.LOW,
      ),
      iosNotificationOptions: const IOSNotificationOptions(
        showNotification: true,
        playSound: false,
      ),
      foregroundTaskOptions: ForegroundTaskOptions(
        eventAction: ForegroundTaskEventAction.repeat(5000),
        autoRunOnBoot: true,
        allowWakeLock: true,
        allowWifiLock: true,
      ),
    );
  }

  Future<void> _loadSettings() async {
    final prefs = await SharedPreferences.getInstance();
    final savedUrl = prefs.getString('relay_server_url') ?? '';
    var savedNodeId = prefs.getString('relay_node_id') ?? '';
    if (savedNodeId.isEmpty) {
      final rnd = Random().nextInt(8999) + 1000;
      savedNodeId = 'android-edge-node-$rnd';
      await prefs.setString('relay_node_id', savedNodeId);
    }
    final savedKey = prefs.getString('relay_secret_key') ?? '';
    final autoStart = prefs.getBool('relay_auto_start') ?? false;

    setState(() {
      _serverUrlCtrl.text = savedUrl;
      _nodeIdCtrl.text = savedNodeId;
      _relayKeyCtrl.text = savedKey;
    });

    _addLog('INFO', 'Node initialized as $savedNodeId');
    if (autoStart && savedUrl.trim().isNotEmpty) {
      await _startRelay();
    }
  }

  Future<void> _saveSettings() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('relay_server_url', _serverUrlCtrl.text.trim());
    await prefs.setString('relay_node_id', _nodeIdCtrl.text.trim());
    await prefs.setString('relay_secret_key', _relayKeyCtrl.text.trim());
    await prefs.setBool('relay_auto_start', _running);
  }

  void _addLog(String level, String message) {
    if (!mounted) return;
    setState(() {
      _logs.insert(
        0,
        RelayLogEntry(
          timestamp: DateTime.now(),
          level: level,
          message: message,
        ),
      );
      if (_logs.length > 120) {
        _logs.removeLast();
      }
    });
  }

  Future<void> _startRelay() async {
    final baseUrl = _serverUrlCtrl.text.trim().replaceAll(RegExp(r'/+$'), '');
    final nodeId = _nodeIdCtrl.text.trim();
    if (baseUrl.isEmpty || !baseUrl.startsWith('http')) {
      _addLog(
        'ERROR',
        'Enter a valid Coordinator Base URL (e.g. https://your-api.example.com) first.',
      );
      return;
    }
    if (nodeId.length < 2) {
      _addLog('ERROR', 'Node ID must be at least 2 characters.');
      return;
    }

    await _saveSettings();
    if (_keepScreenAwake) {
      await WakelockPlus.enable();
    }
    try {
      await FlutterForegroundTask.requestNotificationPermission();
      await FlutterForegroundTask.requestIgnoreBatteryOptimization();
      await FlutterForegroundTask.startService(
        serviceId: 404,
        notificationTitle: 'Caption Edge Relay Online ($nodeId)',
        notificationText: 'Listening for residential subtitle extraction jobs',
        callback: startRelayForegroundCallback,
      );
    } catch (_) {
      // Foreground service optional on desktop/emulators
    }

    _pollTimer?.cancel();
    setState(() {
      _running = true;
    });
    _addLog('SUCCESS', 'Started background relay loop -> $baseUrl');
    unawaited(_pollOnce());
    _pollTimer = Timer.periodic(
      Duration(milliseconds: _pollIntervalMs),
      (_) => unawaited(_pollOnce()),
    );
  }

  Future<void> _stopRelay() async {
    _pollTimer?.cancel();
    _pollTimer = null;
    await WakelockPlus.disable();
    try {
      await FlutterForegroundTask.stopService();
    } catch (_) {}
    setState(() {
      _running = false;
    });
    await _saveSettings();
    _addLog('WARN', 'Relay node stopped.');
  }

  Map<String, String> _buildHeaders() {
    final headers = <String, String>{
      'Content-Type': 'application/json',
      'Accept': 'application/json',
    };
    final key = _relayKeyCtrl.text.trim();
    if (key.isNotEmpty) {
      headers['x-relay-key'] = key;
      headers['Authorization'] = 'Bearer $key';
    }
    return headers;
  }

  Future<void> _pollOnce() async {
    if (!_running) return;
    final baseUrl = _serverUrlCtrl.text.trim().replaceAll(RegExp(r'/+$'), '');
    final nodeId = _nodeIdCtrl.text.trim();
    if (baseUrl.isEmpty) return;

    try {
      final uri = Uri.parse('$baseUrl/api/ingest/youtube/relay-poll');
      final response = await http
          .post(
            uri,
            headers: _buildHeaders(),
            body: jsonEncode({'device_id': nodeId}),
          )
          .timeout(const Duration(seconds: 5));

      if (response.statusCode != 200) {
        _addLog(
          'WARN',
          'Poll HTTP ${response.statusCode}: ${response.body.substring(0, min(80, response.body.length))}',
        );
        return;
      }

      final decoded = jsonDecode(response.body);
      final jobs = (decoded is Map && decoded['jobs'] is List)
          ? (decoded['jobs'] as List)
          : const [];

      if (mounted) {
        setState(() {
          _heartbeatsSent++;
          _lastPollAt = DateTime.now();
          if (decoded is Map && decoded['active_nodes'] is int) {
            _clusterOnlineNodes = decoded['active_nodes'] as int;
          } else if (_clusterOnlineNodes == 0) {
            _clusterOnlineNodes = 1;
          }
        });
      }

      for (final item in jobs) {
        if (item is! Map) continue;
        final videoId = (item['videoId'] ?? item['video_id'] ?? '')
            .toString()
            .trim();
        if (videoId.length != 11 || _inFlightVideos.contains(videoId)) {
          continue;
        }
        _inFlightVideos.add(videoId);
        unawaited(_processJob(baseUrl, nodeId, videoId));
      }
    } catch (e) {
      _addLog('WARN', 'Poll network warning: $e');
    }
  }

  Future<void> _processJob(
    String baseUrl,
    String nodeId,
    String videoId,
  ) async {
    final sw = Stopwatch()..start();
    _addLog('INFO', 'Claimed job for video=$videoId. Extracting captions...');
    try {
      final result = await _extractor.extract(videoId);
      sw.stop();
      final submitUri = Uri.parse('$baseUrl/api/ingest/youtube/relay-submit');
      final resp = await http
          .post(
            submitUri,
            headers: _buildHeaders(),
            body: jsonEncode({
              'device_id': nodeId,
              'video_id': videoId,
              'transcript_text': result.text,
              'caption_kind': result.captionKind,
              'video_title': result.videoTitle,
            }),
          )
          .timeout(const Duration(seconds: 8));

      if (resp.statusCode == 200) {
        if (mounted) {
          setState(() {
            _jobsCompleted++;
          });
        }
        _addLog(
          'SUCCESS',
          'Submitted ${result.text.length} chars (${result.captionKind}) for $videoId in ${sw.elapsedMilliseconds}ms',
        );
      } else {
        throw Exception('HTTP ${resp.statusCode}');
      }
    } catch (e) {
      sw.stop();
      if (mounted) {
        setState(() {
          _jobsFailed++;
        });
      }
      _addLog(
        'ERROR',
        'Job $videoId failed (${sw.elapsedMilliseconds}ms): $e',
      );
      try {
        final submitUri = Uri.parse('$baseUrl/api/ingest/youtube/relay-submit');
        await http
            .post(
              submitUri,
              headers: _buildHeaders(),
              body: jsonEncode({
                'device_id': nodeId,
                'video_id': videoId,
                'transcript_text': '',
                'caption_kind': 'auto',
              }),
            )
            .timeout(const Duration(seconds: 4));
      } catch (_) {}
    } finally {
      _inFlightVideos.remove(videoId);
    }
  }

  Future<void> _runLocalSelfTest() async {
    final videoId = _testVideoCtrl.text.trim();
    if (videoId.length != 11) {
      _addLog('ERROR', 'Enter an 11-character YouTube Video ID to test.');
      return;
    }
    final sw = Stopwatch()..start();
    _addLog('INFO', 'Running local residential extraction test on $videoId...');
    try {
      final res = await _extractor.extract(videoId);
      sw.stop();
      _addLog(
        'SUCCESS',
        'Self-test OK in ${sw.elapsedMilliseconds}ms! Title="${res.videoTitle ?? "N/A"}", Kind=${res.captionKind}, Lang=${res.languageCode}, Chars=${res.text.length}',
      );
    } catch (e) {
      sw.stop();
      _addLog('ERROR', 'Self-test failed (${sw.elapsedMilliseconds}ms): $e');
    }
  }

